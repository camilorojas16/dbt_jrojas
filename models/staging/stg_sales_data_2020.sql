SELECT 
    DATE AS DDATE,
    SALESPERSON,
    CUSTOMERNAME,
    CARMAKE,
    CARMODEL,
    TRY_CAST(CARYEAR AS NUMBER) AS CARYEAR,
    SALEPRICE,
    COMMISSIONRATE AS COMRATE,
    COMMISSIONEARNED AS COMNEAR
FROM 
    {{source("RAW_CAR_SALES", "CAR_SALES")}}
WHERE
    DATE > '2020-01-01'